/** Text holen; fehlt ein Schlüssel in der Sprache, fällt es auf Deutsch zurück. */
export function t(lang, key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.de[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? vars[k] : m));
  return s;
}
